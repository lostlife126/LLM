// Выбор следующего токена из логитов.
//
// Жадный выбор — брать всегда самый вероятный токен — на маленькой модели
// быстро сваливается в повтор одной и той же фразы: самый вероятный
// продолжатель самого вероятного продолжателя обычно возвращает в ту же
// колею. Поэтому выбор делается случайным, а параметры управляют тем,
// насколько.
//
// Порядок преобразований существен и именно такой:
//
//   1. Штраф за повтор — по сырым логитам, до всего остального.
//   2. Температура — делит логиты, растягивая или сжимая распределение.
//   3. top-k — оставить k самых вероятных.
//   4. top-p — оставить наименьшую голову распределения, набирающую p.
//   5. softmax и розыгрыш.
//
// top-k и top-p решают одну задачу с разных сторон. top-k отсекает по числу
// вариантов и не смотрит на вероятности: там, где модель уверена, он всё
// равно оставит k кандидатов, включая нелепые. top-p отсекает по массе и
// подстраивается: на уверенном шаге оставит один вариант, на неоднозначном —
// десятки.

#ifndef LLM_INFER_SAMPLER_H_
#define LLM_INFER_SAMPLER_H_

#include <cstdint>
#include <vector>

#include "core/random.h"

namespace llm {
namespace infer {

struct SamplerConfig {
  // 0 означает жадный выбор. Ниже единицы — распределение заостряется, выше —
  // сглаживается.
  float temperature = 1.0f;

  int64_t top_k = 0;   // 0 — выключено
  float top_p = 0.0f;  // 0 — выключено

  // Делит логит уже встречавшегося токена (а отрицательный — умножает, иначе
  // штраф превратился бы в поощрение). 1.0 — выключено.
  float repetition_penalty = 1.0f;

  // На сколько последних токенов распространяется штраф. Без окна штраф
  // накапливался бы на всём тексте и запретил бы обычные слова.
  int64_t repetition_window = 64;

  uint64_t seed = 1234;
};

// Розыгрыш обратным преобразованием: наименьший номер, на котором
// кумулятивная сумма догоняет порог, среди тех, у кого вероятность
// положительна.
//
// Открыто ради проверки. Внутри sample порог приходит из uniform(), то есть
// лежит в [0, 1), и запасная ветвь — когда сумма не дотянула до порога из-за
// накопленной погрешности — достижима оттуда примерно раз на семнадцать
// миллионов розыгрышей. Задать порог прямо — единственный способ её увидеть.
int32_t choose_by_cumulative(const std::vector<float>& probabilities,
                             double threshold);

class Sampler {
 public:
  explicit Sampler(const SamplerConfig& config);

  // Логиты изменяются на месте. history — уже выбранные токены, нужен штрафу
  // за повтор.
  int32_t sample(std::vector<float>* logits,
                 const std::vector<int32_t>& history);

  const SamplerConfig& config() const { return config_; }

 private:
  SamplerConfig config_;
  Rng rng_;
};

}  // namespace infer
}  // namespace llm

#endif  // LLM_INFER_SAMPLER_H_
