struct NamedParameter {
  std::string name;
  autograd::Var* value;
};

// Что делать при обходе параметров с копиями, подготовленными для инференса.
//
// Обход отдаёт наружу ИЗМЕНЯЕМЫЕ ссылки на веса, и получивший их волен вес
// поменять — так работают и оптимизатор, и загрузка чекпоинта, и импорт чужой
// модели. После этого подготовленная копия молча расходится с весом, поэтому
// обход по умолчанию объявляет её недействительной.
//
// Но не всякий обход что-то меняет: подсчёт параметров складывает их размеры и
// больше ничего с ними не делает. Отзывать копию из-за подсчёта значило бы,
// что печать размера модели незаметно возвращает её в обычную разрядность, —
// а печатается размер как раз рядом с замером скорости, то есть замер мерил бы
// не то, что показывает.
enum class Prepared {
  kRelease,  // копия может разойтись с весом — объявить её недействительной
  kKeep,     // обход только читает — копия остаётся в силе
};

// Нормировка, скрывающая выбор между RMSNorm и LayerNorm.
//
// Вынесена в отдельный класс именно ради сравнения: слоям всё равно, чем
// нормировать, а у LayerNorm есть свободный член, которого у RMSNorm нет, и
// без этой обёртки развилка расползлась бы по всем местам, где стоит
// нормировка.
class Norm {
 public:
  Norm() {}
  explicit Norm(const ModelConfig& config, Rng* rng);

  autograd::Var forward(const autograd::Var& input) const;
  void collect(const std::string& prefix, std::vector<NamedParameter>* out);

  // При дообучении адаптерами масштабы нормировок обычно тоже замораживают:
  // их мало, но менять их значит менять поведение модели глобально, а не
  // точечно.
  void freeze();

 private:
  NormKind kind_ = NormKind::kRmsNorm;
  float eps_ = 1e-5f;
  autograd::Var weight_;
  autograd::Var bias_;  // существует только у LayerNorm
};

// Линейный слой без свободного члена.
//
// Веса хранятся как (вход, выход), а не (выход, вход), как в PyTorch. Тогда
// прямой проход — это просто x * W, без транспонирования на каждом вызове.
//
// Умеет нести низкоранговый адаптер (LoRA). Идея: вместо того чтобы двигать
// всю матрицу весов, к ней прибавляется произведение двух узких матриц
// A (вход x r) и B (r x выход). При r в несколько единиц обучаемых параметров
// становится в десятки раз меньше, а исходные веса не меняются вовсе — их
// можно держать в одном экземпляре и навешивать разные адаптеры под разные
// задачи.
class Linear {
 public:
  Linear() {}
  Linear(int64_t in_features, int64_t out_features, float init_std, Rng* rng);

  autograd::Var forward(const autograd::Var& input) const;
  void collect(const std::string& prefix, std::vector<NamedParameter>* out,
               Prepared prepared = Prepared::kRelease);

  // Замораживает базовый вес: он остаётся значением, но перестаёт быть узлом
  // графа, и градиент до него не доходит.
  void freeze();

  // Навешивает адаптер ранга rank. Масштаб вклада — alpha / rank: так смена
  // ранга не требует заново подбирать скорость обучения.
  void enable_lora(int64_t rank, float alpha, Rng* rng);

  bool has_lora() const { return has_lora_; }

  // Вплавляет адаптер в базовый вес и убирает его. Нужно перед выкладыванием
  // модели: после слияния инференс идёт без всяких дополнительных умножений,
  // как будто адаптера и не было.
  void merge_lora();

  // Переводит вес в половинную разрядность для инференса.
  //
  // Копия, а не замена: обычный вес остаётся на месте. Так устроено потому,
  // что половинная разрядность применяется только на прямом проходе без
  // градиента — по замеру сходимости обучение в ней требует эталонных весов в
  // fp32, то есть смысла заменять нет. Заодно остаётся возможность сравнить
  // два прохода на одной модели, чем и пользуется проверка.
  //
  // Расход — половина размера веса сверх уже занятого. Для инференса это можно
  // было бы убрать, освободив fp32, но тогда модель перестала бы быть
  // обучаемой, а такой односторонний переход лучше делать явно и не здесь.
  //
  // Сколько это даёт. Замер генерации, четыре потока, лучшее из трёх, обе
  // стороны с prepare_inference:
  //
  //              x86 (Xeon, AVX-512)        Raspberry Pi 5 (NEON)
  //   nano    3181 -> 3735 ток/с  1.17x     586 -> 969 ток/с  1.65x
  //   tiny     907 ->  948        1.05x     103 -> 247        2.40x
  //   small    110 ->  231        2.10x      21 ->  57        2.79x
  //
  // Расхождение между машинами велико и объяснимо. Выигрыш здесь — от вдвое
  // меньшего чтения, а значит он появляется там, где машина в чтение упёрлась.
  // Xeon на пресетах поменьше ещё не упёрся, Pi упёрся на всех. Сверх того
  // половинная разрядность вдвое сокращает ШАГ между строками матрицы, а не
  // только объём, и на ARM это стоит отдельных денег: обычная разрядность на
  // широкой матрице выдаёт там 0.65 ГБ/с, то есть впятеро меньше, чем машина
  // умеет.
  //
  // Обратная сторона той же причины: на узких матрицах, целиком помещающихся в
  // кэш, экономить нечего, и на ARM половинная разрядность проигрывает около
  // десяти процентов — две команды FCVTL на каждые восемь весов идут через те
  // же конвейеры, что и умножение с накоплением.
  void pack_half();

  // Пользуется ли прямой проход половинной разрядностью прямо сейчас.
  // Адаптер LoRA её отключает: он живёт в обычной разрядности, и складывать
  // его с базой, посчитанной иначе, значило бы получить третий результат,
  // не равный ни одному из двух.
  bool uses_half() const { return !half_.empty() && !has_lora_; }

  // Объявляет копию половинной разрядности недействительной. Зовётся всюду,
  // где вес может измениться.
  void drop_half();

 private:
  autograd::Var weight_;
  autograd::Var lora_a_;
  autograd::Var lora_b_;
  float lora_scale_ = 0.0f;
  bool has_lora_ = false;
  std::vector<Half> half_;
};

// Размножение голов ключей и значений для GQA.
//
// Вынесено из класса и открыто ради тестов: раскладка голов — это то место,
// где легко ошибиться незаметно. Обе возможные раскладки дают работающую
// модель, обученную с нуля, но соответствие между головами запросов и ключей
// у них разное.
//
// input: (batch, kv_heads, seq, head_dim) -> (batch, kv_heads * repeats, seq,
// head_dim), где голова запроса h пользуется головой ключей h / repeats.
autograd::Var repeat_kv(const autograd::Var& input, int64_t batch,
                        int64_t kv_heads, int64_t repeats, int64_t seq,
                        int64_t head_dim);

class Attention {
 public:
  Attention() {}
  Attention(const ModelConfig& config, Rng* rng);

  void enable_lora(const LoraConfig& config, Rng* rng);
  void merge_lora();
  void freeze();

  // position_offset — абсолютная позиция первого запроса. При обучении нуль,
  // при генерации с KV-кэшем равен длине уже накопленного контекста.
  //
  // cache задаётся только при генерации: тогда input содержит лишь новые
  // позиции, а ключи и значения всех прошлых берутся из кэша. Градиент через
  // кэш не идёт, поэтому этот путь допустим только с выключенной лентой.
  autograd::Var forward(const autograd::Var& input, int64_t position_offset,
                        KvCache* cache = nullptr, int64_t layer = 0,
                        ForwardStats* stats = nullptr) const;
  void collect(const std::string& prefix, std::vector<NamedParameter>* out,
               Prepared prepared = Prepared::kRelease);

  void pack_half();

 private:
  autograd::Var split_heads(const autograd::Var& input, int64_t batch,
                            int64_t seq, int64_t heads) const;

  ModelConfig config_;
  Linear query_;
  Linear key_;
  Linear value_;
  Linear output_;
  // Масштабы нормировки запросов и ключей; существуют только при qk_norm.
  autograd::Var query_norm_;
  autograd::Var key_norm_;
};

// FFN: либо SwiGLU, либо обычный двухматричный слой с GELU.
//
// У SwiGLU три матрицы: вентиль silu(gate(x)) умножается на up(x)
// поэлементно, то есть сеть сама решает, какие каналы пропустить дальше, а
// какие подавить, и решение зависит от входа. У варианта с GELU две матрицы и
// никакого вентиля — так было в исходном трансформере.
//
// Чтобы сравнение было о устройстве, а не о размере, ширину второго варианта
// берут в полтора раза больше: тогда числа параметров совпадают.
class Mlp {
 public:
  Mlp() {}
  Mlp(const ModelConfig& config, Rng* rng);

  autograd::Var forward(const autograd::Var& input,
                        ForwardStats* stats = nullptr) const;
  void collect(const std::string& prefix, std::vector<NamedParameter>* out,
               Prepared prepared = Prepared::kRelease);

  void enable_lora(const LoraConfig& config, Rng* rng);
  void merge_lora();
  void freeze();

  void pack_half();

 private:
  FfnKind kind_ = FfnKind::kSwiGlu;
  Linear gate_;  // существует только у SwiGLU
  Linear up_;
  Linear down_;
};

// Блок трансформера.
//
// Пре-нормировка: нормируется вход подслоя, а к результату прибавляется
// НЕнормированный остаток. Пост-нормировка: нормируется уже сумма.
//
// Порядок существен. При пост-нормировке нормировка стоит на пути остатка, и
// градиент на каждом слое проходит через неё. При пре-нормировке путь остатка
// от выхода до входа — чистое сложение, и градиент доходит до первого слоя без
// искажений. Насколько это важно на четырёх слоях — вопрос к замеру, а не к
// рассуждению.
class Block {
 public:
  Block() {}
  Block(const ModelConfig& config, Rng* rng);

  autograd::Var forward(const autograd::Var& input, int64_t position_offset,
                        KvCache* cache = nullptr, int64_t layer = 0,
                        ForwardStats* stats = nullptr) const;
  void collect(const std::string& prefix, std::vector<NamedParameter>* out,
               Prepared prepared = Prepared::kRelease);

  void enable_lora(const LoraConfig& config, Rng* rng);
  void merge_lora();
  void freeze();

  void pack_half();

 private:
  ModelConfig config_;
  Norm attention_norm_;
  Norm mlp_norm_;
  Attention attention_;
  Mlp mlp_;
};

class Model {
 public:
  Model(const ModelConfig& config, uint64_t seed);

  const ModelConfig& config() const { return config_; }

  // ids — batch * seq идентификаторов в порядке (батч, позиция).
  // Возвращает логиты формы (batch, seq, vocab).
  autograd::Var forward(const std::vector<int32_t>& ids, int64_t batch,
                        int64_t seq, int64_t position_offset = 0,
                        KvCache* cache = nullptr,
                        ForwardStats* stats = nullptr) const;

  // Логиты только последней позиции — то, что нужно генерации. Форма
  // (batch, vocab).
  autograd::Var forward_last(const std::vector<int32_t>& ids, int64_t batch,
                             int64_t seq, int64_t position_offset = 0,
                             KvCache* cache = nullptr) const;

  // Потери на предсказании следующего токена: каждая позиция предсказывает
  // следующую, последняя отбрасывается — ей нечего предсказывать.
  autograd::Var loss(const std::vector<int32_t>& ids, int64_t batch,
                     int64_t seq, ForwardStats* stats = nullptr) const;

  // Все параметры: и обучаемые, и замороженные. Чекпоинту нужны все.
  std::vector<NamedParameter> parameters();
  int64_t parameter_count();

  // Только те, до которых доходит градиент. Оптимизатор берёт их: заводить
  // моменты Адама на замороженный вес — чистая трата памяти.
  std::vector<NamedParameter> trainable_parameters();
  int64_t trainable_parameter_count();

  // Переводит модель в режим дообучения адаптерами: базовые веса
  // замораживаются, на выбранные проекции навешиваются адаптеры.
  void enable_lora(const LoraConfig& config);

  // Вплавляет все адаптеры в базовые веса.
  void merge_lora();

  // Переводит веса всех линейных слоёв в половинную разрядность для инференса.
  //
  // Действует только на прямой проход без градиента: обучение после этого
  // идёт как прежде, в обычной разрядности. Так и задумано — по замеру
  // сходимости веса в половинной разрядности обучение выдерживает хуже, чем
  // активации, и эталонная копия в fp32 нужна всё равно.
  //
  // При связанных эмбеддингах таблица токенов работает и выходной проекцией,
  // причём транспонированной. Транспонированная копия готовится здесь же, один
  // раз: gemm_half_b транспонирования не умеет, а при однократной подготовке
  // проще переложить, чем учить.
  void pack_half();

  // Подготовка к инференсу в обычной разрядности.
  //
  // Нужна из-за связанных эмбеддингов. Выходная проекция при них — это та же
  // таблица токенов, только транспонированная, а умножение на транспонированную
  // матрицу проходит через упаковку с перестановкой. Упаковка эта не
  // кэшируется и делается заново на каждый токен: для пресета small это
  // перекладывание двенадцати мегабайт на каждое слово.
  //
  // Замер на x86, форма выходной проекции, m = 1:
  //
  //   nano  128 x 1024    0.023 мс -> 0.061 мс   2.6 раза
  //   tiny  256 x 4096    0.074 мс -> 0.777 мс  10.5 раза
  //   small 384 x 8192    0.232 мс -> 2.521 мс  10.9 раза
  //
  // Здесь таблица перекладывается один раз. Численно это ничего не меняет —
  // упаковка переставляет значения, но порядок накопления по глубине у обоих
  // путей один и тот же, и результаты совпадают побитово. Проверено.
  //
  // Расход — ещё одна таблица эмбеддингов в памяти. Поэтому вызывать явно, а
  // не втихую при первом проходе: обучению это не нужно, а памяти стоит.
  //
  // Выигрыш машинно-зависим, и это стоит знать. На x86 генерация пресета tiny
  // ускорилась вдвое (453 -> 907 токенов/с), на Raspberry Pi 5 — ни на сколько
  // (20.2 -> 20.6 у small), а у nano там вышло на восемь процентов хуже.
  //
  // Причина в том, что у упаковки с перестановкой есть второе свойство: она
  // дорога, но после неё ядро читает панель ПОДРЯД. Готовая транспонированная
  // таблица упаковку убирает — и ядро читает матрицу с шагом в целую строку,
  // до 32 килобайт. На x86 разница между «подряд» и «с шагом» невелика, и
  // экономия на упаковке побеждает; на ARM шаг дорог, и размен обнуляется.
  //
  // Это не повод убирать подготовку: побитово результат тот же, на одной
  // машине выигрыш большой, на другой его нет. Но правильное решение лежит
  // дальше — хранить таблицу сразу в раскладке упакованной панели, и тогда не
  // будет ни перекладывания на каждый токен, ни чтения с шагом.
  void prepare_inference();

 private:
  // Общий обход параметров. Наружу он уходит двумя дверями: parameters(), где
  // ссылки отдаются на изменение, и подсчёт, где они только читаются, — отсюда
  // и признак.
  std::vector<NamedParameter> collect_parameters(Prepared prepared);

  ModelConfig config_;
  autograd::Var token_embedding_;
  autograd::Var position_embedding_;  // только при обучаемых позициях
  std::vector<Block> blocks_;
  Norm final_norm_;
  Linear lm_head_;  // не используется при связанных эмбеддингах

  // Таблица эмбеддингов, уложенная транспонированной и в половинной
  // разрядности: d_model строк, vocab столбцов. Пуста, пока pack_half не
  // вызван или эмбеддинги не связаны.
  std::vector<Half> half_embedding_transposed_;

  // Она же в обычной разрядности. Не определена, пока prepare_inference не
  // вызван или эмбеддинги не связаны.
  autograd::Var embedding_transposed_;
};

