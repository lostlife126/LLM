// Настройки дообучения низкоранговыми адаптерами.
//
// LoRA исходит из наблюдения: дообучение под новую задачу сдвигает веса
// незначительно и, как оказывается, этот сдвиг почти целиком укладывается в
// матрицу малого ранга. Значит вместо того чтобы менять матрицу W размера
// (вход x выход), можно прибавить к ней произведение A * B, где A — (вход x r),
// B — (r x выход), а r измеряется единицами.
//
// Практических следствий три. Обучаемых параметров становится в десятки раз
// меньше, а с ними и памяти под моменты оптимизатора. Исходные веса не
// меняются, поэтому под разные задачи можно держать один экземпляр модели и
// набор маленьких адаптеров. И адаптер можно вплавить обратно в веса, после
// чего инференс идёт вообще без накладных расходов.

#ifndef LLM_NN_LORA_H_
#define LLM_NN_LORA_H_

#include <cstdint>

namespace llm {
namespace nn {

struct LoraConfig {
  int64_t rank = 8;

  // Вклад адаптера умножается на alpha / rank. Деление на ранг нужно, чтобы
  // при смене ранга не приходилось заново подбирать скорость обучения:
  // масштаб вклада остаётся тем же.
  float alpha = 16.0f;

  // К каким проекциям цеплять адаптеры. Классический выбор — только запросы и
  // значения внимания: этого обычно достаточно, а параметров добавляется
  // меньше всего.
  bool attention_query = true;
  bool attention_key = false;
  bool attention_value = true;
  bool attention_output = false;
  bool ffn = false;

  // Разброс начальной инициализации матрицы A. Матрица B начинается с нуля —
  // это ключевая деталь: пока B нулевая, адаптер не даёт вклада вовсе, и
  // модель в начале дообучения в точности совпадает с исходной. Если бы обе
  // матрицы начинались случайными, дообучение стартовало бы со сломанной
  // модели.
  float init_std = 0.02f;

  uint64_t seed = 4242;
};

}  // namespace nn
}  // namespace llm

#endif  // LLM_NN_LORA_H_
