// Диагностика прямого прохода.
//
// Потери говорят, насколько модель ошибается, но ничего не говорят о том, что
// внутри неё происходит. Здесь собраны величины, по которым видно поведение
// модели, а не только её результат:
//
//   RMS остатка по слоям — растёт ли остаточный поток с глубиной. Рост в разы
//   означает, что поправка на инициализацию выходных проекций не справляется,
//   и активации уходят из рабочего диапазона.
//
//   Относительная энтропия внимания — насколько размазано внимание. Считается
//   как энтропия строки softmax, делённая на максимально возможную для этой
//   строки: единица означает равномерное внимание (голова ничего не выбирает),
//   ноль — предельно сосредоточенное. По ходу обучения она обычно падает: это
//   и есть специализация голов, видимая числом.
//
//   Доля открытых вентилей SwiGLU — какая часть каналов пропускается дальше.
//   Схлопывание к нулю или к единице означает, что вентиль перестал что-либо
//   выбирать и FFN выродился в обычный.
//
// Всё считается только когда структура передана: в обычном обучении лишние
// редукции не нужны.

#ifndef LLM_NN_DIAGNOSTICS_H_
#define LLM_NN_DIAGNOSTICS_H_

#include <cstdint>
#include <vector>

namespace llm {
namespace nn {

struct ForwardStats {
  // По одному значению на слой.
  std::vector<float> residual_rms;
  std::vector<float> attention_entropy;
  std::vector<float> gate_open_fraction;

  // Чистая перекрёстная энтропия, без вспомогательных слагаемых.
  //
  // Оптимизируется сумма потерь и штрафов, а сравнивать прогоны надо по одной
  // и той же величине: иначе включение Z-loss «ухудшало» бы модель просто
  // потому, что к её потерям добавилось слагаемое.
  float cross_entropy = 0.0f;

  // Качество предсказания; заполняется в Model::loss.
  float top1_accuracy = 0.0f;

  // Энтропия предсказанного распределения в натах. Показывает уверенность
  // модели: на старте близка к log(vocab), по ходу обучения падает.
  float prediction_entropy = 0.0f;

  // Логарифм суммы экспонент выходных логитов, усреднённый по строкам. Softmax
  // к нему нечувствителен, поэтому логиты вольны дрейфовать от нуля целой
  // группой — и в больших моделях дрейфуют, отъедая точность float. Это та
  // величина, которую штрафует Z-loss: по ней видно, есть ли что штрафовать.
  float log_z = 0.0f;

  // Потери по четвертям окна. Модель обязана предсказывать конец окна лучше
  // начала: там больше контекста. Если разницы нет, контекст не используется.
  std::vector<float> loss_by_quarter;

  void clear() {
    residual_rms.clear();
    attention_entropy.clear();
    gate_open_fraction.clear();
    loss_by_quarter.clear();
    cross_entropy = 0.0f;
    top1_accuracy = 0.0f;
    prediction_entropy = 0.0f;
    log_z = 0.0f;
  }
};

}  // namespace nn
}  // namespace llm

#endif  // LLM_NN_DIAGNOSTICS_H_
