// Чекпоинт: веса модели плюс конфигурация, с которой они совместимы.
//
// Формат двоичный и самоописывающийся. Хранить одни только веса недостаточно:
// чтобы их прочитать, нужно знать форму модели, а держать её отдельно от файла
// значит однажды перепутать.
//
// Порядок байтов не преобразуется. Все целевые платформы проекта
// little-endian, и вместо того чтобы писать преобразование, которое негде
// проверить, файл содержит метку: при чтении на машине с другим порядком байт
// или другим представлением float загрузка честно откажется, а не выдаст мусор.

#ifndef LLM_SERIALIZE_CHECKPOINT_H_
#define LLM_SERIALIZE_CHECKPOINT_H_

#include <cstdint>
#include <string>

#include "nn/model.h"

namespace llm {
namespace serialize {

// step записывается вместе с весами: возобновлённое обучение должно
// продолжить расписание скорости с того же места, а не начать разогрев заново.
void save_checkpoint(const std::string& path, nn::Model* model, int64_t step);

// Загружает веса в существующую модель. Конфигурация в файле обязана совпадать
// с конфигурацией модели.
int64_t load_checkpoint(const std::string& path, nn::Model* model);

// Читает только конфигурацию — чтобы создать модель нужной формы, прежде чем
// загружать в неё веса.
nn::ModelConfig read_config(const std::string& path);

}  // namespace serialize
}  // namespace llm

#endif  // LLM_SERIALIZE_CHECKPOINT_H_
