// Перенос весов HuggingFace Llama в нашу модель.
//
// Архитектура та же, и именно поэтому опасно. Расхождения здесь не в том, что
// чего-то нет, а в том, что одно и то же записано иначе, — и каждое из них
// даёт работающую модель с неправильными ответами.
//
// Расхождение первое: ориентация матриц. torch.nn.Linear(in, out) хранит вес
// как (out, in) и считает x @ W.T. Мы храним (in, out) и считаем x @ W. Значит
// каждую матрицу нужно транспонировать. Ошибиться нельзя: при in == out
// (а так у проекций внимания) форма совпадёт и проверка размеров смолчит.
//
// Расхождение второе, тонкое: раскладка каналов для RoPE. Мы вращаем соседние
// пары — каналы (0,1), (2,3), ... Реализация Llama в transformers вращает
// половинки: канал j в паре с каналом j + head_dim/2. Частоты в обеих те же
// самые, различается только то, какие каналы считаются парой. Отсюда
// перестановка: наш канал 2i берёт их канал i, наш 2i+1 — их i + head_dim/2.
//
// Перестановка применяется только к запросам и ключам: значения не вращаются,
// а выходная проекция работает уже с результатом внимания. И применяется она
// внутри каждой головы отдельно — головы лежат в матрице подряд.
//
// Проверить это рассуждение можно, не имея чужих весов: наша же модель
// записывается в чужом формате со всеми преобразованиями, читается обратно и
// обязана дать те же логиты до последнего бита. Круговая проверка не докажет,
// что мы правильно поняли transformers, но докажет, что преобразования
// обратимы и применены к тем матрицам, к которым надо.

#ifndef LLM_SERIALIZE_HF_IMPORT_H_
#define LLM_SERIALIZE_HF_IMPORT_H_

#include <string>
#include <vector>

#include "nn/model.h"
#include "serialize/hf_config.h"
#include "serialize/safetensors.h"

namespace llm {
namespace serialize {

// Перестановка каналов внутри каждой головы: половинки transformers <->
// наши соседние пары. Открыты ради тестов — это то самое место, где ошибка
// даёт работающую модель с неправильными ответами, и проверять его надо
// отдельно от всего остального.
//
// Вход — матрица (heads * head_dim, in_features) в раскладке transformers,
// то есть до транспонирования: переставляются строки, они же выходные каналы.
Tensor halves_to_pairs(const Tensor& input, int64_t heads, int64_t head_dim);
Tensor pairs_to_halves(const Tensor& input, int64_t heads, int64_t head_dim);

struct HfImportReport {
  int64_t tensors_used = 0;
  int64_t values_copied = 0;
  // Тензоры файла, до которых мы не дотянулись. Пустой список — хороший
  // признак: значит, в файле не осталось ничего, о чём мы не знаем.
  std::vector<std::string> unused;
};

// Загружает веса в готовую модель. Форма модели обязана совпадать с описанием
// из config.json — за этим следит вызывающий, создавая модель по нему же.
HfImportReport import_hf_weights(const SafeTensors& file,
                                 const HfConfig& config, nn::Model* model);

// Обратное преобразование: наша модель — в набор тензоров в раскладке
// HuggingFace. Нужно ровно затем, чтобы проверить прямое.
struct NamedTensor {
  std::string name;
  Tensor value;
};

std::vector<NamedTensor> export_hf_weights(nn::Model* model);

// Описание модели в виде config.json — тоже для круговой проверки.
std::string hf_config_json(const nn::ModelConfig& config);

// Записывает тензоры в файл safetensors. Отдельно от экспорта, чтобы запись
// формата проверялась независимо от раскладки весов.
void write_safetensors(const std::string& path,
                       const std::vector<NamedTensor>& tensors);

}  // namespace serialize
}  // namespace llm

#endif  // LLM_SERIALIZE_HF_IMPORT_H_
