// Пул потоков: один на процесс, создаётся при первом обращении.
//
// Зачем пул, а не std::thread на каждое умножение. Обучение делает порядка
// сотни умножений матриц на шаг, шагов — тысячи. Создание потока стоит
// десятки микросекунд, а само умножение на форме внимания занимает столько
// же; платить за создание в каждом вызове значит отдать весь выигрыш обратно.
// Пул создаёт потоки один раз, дальше — только пробуждение на условной
// переменной.
//
// Почему интерфейс — parallel_for по номерам задач, а не очередь задач с
// std::function на каждую. Задач у нас ровно столько, сколько ядер: работа
// делится заранее, крупными куском на поток. Очередь мелких задач добавила бы
// аллокацию и захват мьютекса на каждую, а выиграть от динамической
// балансировки нам нечего — куски заведомо одинаковые.
//
// Вызывающий поток тоже работает. Иначе при четырёх ядрах пришлось бы создать
// четыре потока и держать пятый спящим, а это лишнее переключение контекста на
// каждый вызов.
//
// Вложенность запрещена и обрабатывается молча: parallel_for, вызванный
// изнутри задачи, выполняет её последовательно. Это важно, потому что
// параллельные точки в проекте вложены естественным образом — matmul делит
// батч, gemm делит матрицу, — и без такой проверки внутренний вызов ждал бы
// потоков, которые уже заняты им самим, то есть намертво.
//
// Исключения. LLM_CHECK бросает, а исключение, вылетевшее из потока, убивает
// процесс через std::terminate. Поэтому задачи оборачиваются в try, первое
// исключение сохраняется и перебрасывается в вызывающем потоке — снаружи
// параллельность не видна и здесь тоже.

#ifndef LLM_CORE_THREAD_POOL_H_
#define LLM_CORE_THREAD_POOL_H_

#include <cstdint>
#include <functional>

namespace llm {

// Сколько задач имеет смысл создавать. Всегда не меньше единицы.
//
// По умолчанию — число ядер, доступных процессу; переменная окружения
// LLM_THREADS переопределяет его. Переменная нужна не для удобства, а для
// замера: сравнение «на одном ядре против четырёх» должно запускать один и
// тот же бинарник, иначе сравниваются ещё и настройки сборки.
int parallel_width();

// Меняет ширину. Ноль означает «по числу ядер». Значение больше числа
// созданных потоков обрезается: больше участников, чем есть, не бывает.
//
// Величина глобальная, и менять её на ходу нельзя: предполагается, что это
// делается до начала счёта — в разборе аргументов или в замере между сериями.
void set_parallel_width(int width);

// Выполняет task(0) ... task(tasks - 1), возможно параллельно, и возвращается
// только когда выполнены все.
//
// Задачи обязаны быть независимыми: порядок и поток, в котором выполнится
// каждая, не определены. Одновременный вызов из двух разных потоков
// допустим, но второй дождётся первого — пул один.
void parallel_for(int tasks, const std::function<void(int)>& task);

// Делит отрезок [0, count) на куски и выполняет fn(begin, end) для каждого,
// возможно параллельно.
//
// grain — наименьшее число элементов, которое стоит отдавать одному потоку.
// Задавать его обязан вызывающий, и это не придирка: вход в параллельную
// область стоит около двух микросекунд, а сколько это элементов — зависит от
// того, что с элементом делается. Для поэлементного сложения, упирающегося в
// память, это тысячи элементов; для строки softmax с экспонентами — сотни.
//
// Куски всегда одинаковой длины с точностью до одного элемента, и номер куска
// однозначно определяет его границы. Поэтому результат не зависит от числа
// потоков, если сама fn этого не нарушает.
void parallel_range(std::int64_t count, std::int64_t grain,
                    const std::function<void(std::int64_t, std::int64_t)>& fn);

// Разбор значения LLM_THREADS. Ноль означает «не задано»; нечисловое
// значение — отказ, а не молчаливый ноль.
//
// Открыто ради тестов, и не для порядка: проверить это через саму переменную
// окружения нельзя, не трогая окружение всего процесса, а правило разбора —
// ровно то место, где ошибка не видна. LLM_THREADS=4x при разборе без
// проверки хвоста дала бы четыре, а LLM_THREADS=x4 — число ядер, и замер «на
// одном ядре против четырёх» измерял бы не то, что написано в его подписи.
int parse_thread_count(const char* text);

// Идёт ли вызов изнутри задачи parallel_for. Нужно тем, кто решает, делить
// ли работу: изнутри делить уже нечем.
bool inside_parallel_region();

}  // namespace llm

#endif  // LLM_CORE_THREAD_POOL_H_
