// Хранение чисел в половинной разрядности.
//
// Это тип хранения, а не арифметики. Вычисления во всём проекте идут в float:
// микроядра, суммы, нормировки — всё как было. Половинная разрядность нужна
// ровно для того, чтобы вдвое сократить байты, которые читаются из памяти, и
// вдвое — место, которое веса занимают. Замер трафика GEMM говорит, где это
// окупается: при генерации по одному токену веса дают две трети всех
// прочитанных байт, при обучении батчами — четверть.
//
// Почему отдельный тип, а не поле dtype у Tensor. Комментарий в tensor.h
// отвергает обобщение по типу элемента: диспетчеризация в начале каждой
// операции похоронила бы читаемость. Довод остаётся верным, но к весам он не
// относится — вес не бывает операндом произвольной операции, он всегда только
// читается умножением матриц. Поэтому половинная разрядность появляется как
// отдельное хранилище рядом, а не как вариант у всего.
//
// Почему структура, а не using Half = uint16_t. Над разрядным представлением
// арифметика бессмысленна, но компилятор её разрешит: h + h сложило бы битовые
// картинки и промолчал бы. Структура это запрещает, а стоит она нисколько —
// размер и раскладка те же, и memcpy с ней работает как с uint16_t.

#ifndef LLM_CORE_HALF_H_
#define LLM_CORE_HALF_H_

#include <cstdint>

#include "core/fp16.h"

namespace llm {

struct Half {
  uint16_t bits;
};

static_assert(sizeof(Half) == 2, "Half обязан занимать ровно два байта");

inline Half half_from_float(float value) {
  Half result;
  result.bits = to_fp16(value);
  return result;
}

inline float float_from_half(Half value) { return from_fp16(value.bits); }

// Пакетное преобразование. Отдельными функциями, а не циклом на месте вызова:
// преобразование стоит на горячем пути упаковки панелей, и если его придётся
// ускорять, менять надо будет одно место.
//
// Оговорка про краевые значения. Преобразование определено для конечных чисел
// и нуля; бесконечность и NaN сохраняют свой класс, но разряды мантиссы NaN
// не оговариваются. Весам это безразлично — NaN в весах означает, что обучение
// уже разошлось, — а обещать побитовое совпадение там, где его можно потерять
// при первой же векторизации, не стоит.
void floats_to_half(const float* source, Half* destination, int64_t count);
void half_to_floats(const Half* source, float* destination, int64_t count);

}  // namespace llm

#endif  // LLM_CORE_HALF_H_
