// Какие векторные расширения есть у процессора, на котором мы сейчас бежим.
//
// Зачем это вообще нужно. Векторное ядро можно было бы включить флагом
// компилятора на весь проект, и так проще всего — но тогда бинарник,
// собранный на машине с AVX-512, падает с SIGILL на машине без него, причём
// не в понятном месте, а на первой же встреченной инструкции. Для проекта,
// который собирают и запускают в разных местах, это плохой размен.
//
// Поэтому иначе: сами ядра помечены атрибутом target и компилируются под свои
// наборы инструкций, а выбор между ними делается здесь, один раз при первом
// обращении. Всё остальное собирается под базовый x86-64 и работает везде.
//
// Проверка идёт через __builtin_cpu_supports — это CPUID, завёрнутый
// компилятором, и он есть и у GCC, и у clang. Писать CPUID руками смысла нет:
// у него хватает тонкостей с проверкой того, сохраняет ли операционная
// система состояние регистров, и компилятор их уже учёл.

#ifndef LLM_CORE_CPU_H_
#define LLM_CORE_CPU_H_

#include <string>

namespace llm {

struct CpuFeatures {
  bool avx2 = false;
  bool fma = false;
  bool avx512f = false;
  bool avx512bw = false;
  bool avx512vl = false;

  // Годится ли процессор для соответствующего ядра. AVX2 без FMA бессмыслен:
  // выигрыш умножения с накоплением и есть главное, что нам нужно.
  bool has_avx2_fma() const { return avx2 && fma; }
  bool has_avx512() const { return avx512f && avx512bw && avx512vl && fma; }

  std::string to_string() const;
};

// Считается один раз при первом обращении.
const CpuFeatures& cpu_features();

// Число ядер, доступных процессу. Ноль означает, что узнать не удалось —
// тогда вызывающий берёт единицу.
int detect_core_count();

}  // namespace llm

#endif  // LLM_CORE_CPU_H_
