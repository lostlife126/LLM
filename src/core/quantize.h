// Округление тензора до пониженной разрядности.
//
// Отдельный файл, а не функция рядом с форматом, потому что здесь решается то,
// чего в самом формате нет: МАСШТАБ.
//
// Зачем он нужен. Веса этой модели рождаются с разбросом 0.02, а наименьшее
// нормальное значение E4M3 — это 2^-6, то есть 0.0156. Больше половины весов
// попадает в субнормальную область, где всего восемь уровней с шагом 2^-9: вес
// 0.005 округлился бы с ошибкой сорок процентов, а вес 0.001 — в нуль или в
// удвоенное значение. Провалилось бы это не потому, что восьми разрядов мало, а
// потому что диапазон порядка формата стоит не там, где живут данные. Замер без
// масштаба ответил бы на другой вопрос.
//
// Поэтому масштаб на тензор: наибольшее по модулю значение отображается на
// верхний край формата, и весь диапазон порядка оказывается занят делом. Так
// устроены все работающие реализации fp8, и сравнивать надо с ними.
//
// Масштаб — СТЕПЕНЬ ДВОЙКИ, и это не упрощение ради простоты. Умножение и
// деление на степень двойки точны, значит масштабирование не добавляет к
// погрешности ни одного разряда, и измеренная потеря качества относится к
// формату, а не к арифметике вокруг него. В настоящем ядре это вдобавок
// бесплатно — сдвиг поля порядка.
//
// Что НЕ делается здесь: масштаб на блок из 32 весов, на котором держатся
// четырёхразрядные схемы. Для восьми разрядов масштаба на тензор достаточно, а
// блочный — отдельная конструкция со своим хранением и своей распаковкой.

#ifndef LLM_CORE_QUANTIZE_H_
#define LLM_CORE_QUANTIZE_H_

#include "core/tensor.h"

namespace llm {

enum class Precision {
  kFp32,        // ничего не делать
  kFp16,        // половинная разрядность, без масштаба — её диапазона хватает
  kFp8E4M3,     // с масштабом на тензор
  kFp8E5M2,     // с масштабом на тензор
  // E4M3 без масштаба. Существует ровно затем, чтобы показать числом, почему
  // масштаб обязателен: без него формат промахивается мимо данных, и вывод о
  // применимости восьми разрядов получился бы неверным.
  kFp8E4M3NoScale,
};

// Разбор имени: fp32, fp16, e4m3, e5m2, e4m3-raw. Возвращает false, если имя
// незнакомо.
bool parse_precision(const char* name, Precision* out);
const char* precision_name(Precision precision);

// Округляет содержимое тензора на месте. Тензор обязан быть плотным: вид на
// чужой буфер округлять нельзя, это испортило бы данные владельца.
void quantize(Tensor* tensor, Precision precision);

// Показатель масштаба, который выберет quantize для этого тензора: наименьшее
// целое e, при котором max|x| / 2^e не превосходит верхнего края формата.
// Открыто ради тестов и диагностики — по нему видно, попали ли данные в
// диапазон формата или уткнулись в его край.
int scale_exponent(const Tensor& tensor, Precision precision);

}  // namespace llm

#endif  // LLM_CORE_QUANTIZE_H_
