// Разбор UTF-8.
//
// Нужен предтокенизации: правила вида «одна или больше букв» работают с
// кодовыми точками, а на входе байты.
//
// Неправильная последовательность не считается ошибкой. Текст приходит
// снаружи, и падать на нём нельзя; байт-левел BPE всё равно кодирует байты,
// а не символы, поэтому испорченный участок просто не попадёт ни в буквы, ни
// в цифры и уйдёт в разряд прочих символов — ровно то поведение, которое даёт
// эталонная реализация.

#ifndef LLM_TOKENIZER_UTF8_H_
#define LLM_TOKENIZER_UTF8_H_

#include <cstddef>
#include <cstdint>
#include <string>

namespace llm {

struct Utf8Char {
  uint32_t code = 0;
  // Сколько байт занято. Всегда не меньше единицы, чтобы разбор двигался
  // вперёд даже на мусоре.
  int bytes = 1;
  bool valid = false;
};

// Декодирует одну кодовую точку из data[0..size). При неверной
// последовательности возвращает один байт и valid = false.
Utf8Char decode_utf8(const char* data, std::size_t size);

// Дописывает кодовую точку в UTF-8.
void append_utf8(uint32_t code, std::string* out);

}  // namespace llm

#endif  // LLM_TOKENIZER_UTF8_H_
