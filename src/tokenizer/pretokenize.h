// Предтокенизация: разбиение текста на куски перед слияниями BPE.
//
// Шаг выглядит второстепенным, а определяет всё. Слияния никогда не
// перешагивают границу куска, поэтому от того, где эта граница проходит,
// зависит, какие токены вообще могут получиться. Разбиение, отличающееся от
// авторского, даёт другие номера токенов — модель получит на вход не тот
// текст и ответит связно и не по делу.
//
// В tokenizer.json правило записано регулярным выражением с юникодными
// классами. Общего разбора таких выражений здесь нет, и это осознанный
// выбор: написать половину движка регулярных выражений — значит завести
// собственный набор расхождений с эталоном. Вместо этого узнаются известные
// образцы, каждый реализован вручную, а незнакомое выражение — отказ с
// печатью самого выражения. Отказ здесь безопаснее догадки: неверная
// токенизация не проявляется ни падением, ни бессмыслицей.

#ifndef LLM_TOKENIZER_PRETOKENIZE_H_
#define LLM_TOKENIZER_PRETOKENIZE_H_

#include <string>
#include <vector>

#include "core/str_view.h"

namespace llm {

enum class PretokenizeRule {
  // 'ы|'т|... | ?\p{L}+ | ?\p{N}+ | ?[^\s\p{L}\p{N}]+ | \s+(?!\S) | \s+
  //
  // Образец GPT-2. Числа склеиваются в сколь угодно длинные куски, поэтому
  // «1234567» — один кусок, и модель видит его как одно целое.
  kGpt2,

  // (?i:'ы|'т|...) | [^\r\n\p{L}\p{N}]?\p{L}+ | \p{N}{1,3} |
  //  ?[^\s\p{L}\p{N}]+[\r\n]* | \s*[\r\n]+ | \s+(?!\S) | \s+
  //
  // Образец GPT-4, он же у Llama 3 и у моделей на её токенизаторе. Два
  // существенных отличия от предыдущего: числа режутся по три цифры (это
  // заметно улучшает арифметику) и перевод строки обрабатывается отдельно, а
  // не попадает в общий разряд пробелов.
  kGpt4,
};

// Разбивает текст на куски. Куски идут подряд и покрывают весь вход без
// потерь: склеив их, получится исходная строка.
std::vector<StrView> pretokenize(StrView text, PretokenizeRule rule);

// Узнаёт правило по записи регулярного выражения из tokenizer.json.
// Возвращает false, если образец незнаком.
bool recognize_pretokenizer(const std::string& pattern, PretokenizeRule* rule);

// Запись известного образца — для сообщений об ошибке и для тестов.
const char* pretokenizer_pattern(PretokenizeRule rule);

}  // namespace llm

#endif  // LLM_TOKENIZER_PRETOKENIZE_H_
