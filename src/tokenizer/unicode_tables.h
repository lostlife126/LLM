// Категории Unicode, нужные предтокенизации чужих моделей.
//
// Предтокенизатор в tokenizer.json задан регулярным выражением, и в нём стоят
// классы \p{L} и \p{N} — «любая буква», «любая цифра». Это не украшение: от
// того, где проходит граница слова, зависит, какие токены получатся, а от них
// — что модель увидит на входе.
//
// std::regex этих классов не понимает ни в одной версии стандарта. Проверено:
// в C++20 выражение \p{L} отвергается как ошибка, а [[:alpha:]] берёт только
// ASCII — на строке "abcпривет" останавливается после "abc". Так что дело не
// в возрасте стандарта, и обновление его не решает.
//
// Значит нужны сами диапазоны кодовых точек. Их под восемьсот, выписывать
// руками нечего и думать, поэтому таблица генерируется из базы Unicode
// скриптом tools/gen_unicode_tables.py и кладётся в репозиторий готовой. Во
// время сборки и работы никаких зависимостей это не добавляет.

#ifndef LLM_TOKENIZER_UNICODE_TABLES_H_
#define LLM_TOKENIZER_UNICODE_TABLES_H_

#include <cstdint>

namespace llm {

// Категории L* (все буквы) и N* (все числовые символы) соответственно.
bool is_unicode_letter(uint32_t code);
bool is_unicode_number(uint32_t code);

}  // namespace llm

#endif  // LLM_TOKENIZER_UNICODE_TABLES_H_
