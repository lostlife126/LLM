// Расписание скорости обучения: линейный разогрев плюс косинусное затухание.
//
// Зачем разогрев. В самом начале моменты Адама ещё не накоплены, оценка
// второго момента близка к нулю, и шаг получается непредсказуемо большим.
// Несколько сотен шагов с нарастающей скоростью дают моментам набраться, и
// обучение не срывается на первых же батчах.
//
// Зачем затухание. К концу обучения нужен мелкий шаг, чтобы не перепрыгивать
// минимум. Косинус выбран не из мистики: он убывает медленно в начале, где
// ещё можно двигаться быстро, и медленно в конце, где уже почти пришли, а
// основное снижение приходится на середину.

#ifndef LLM_TRAIN_SCHEDULE_H_
#define LLM_TRAIN_SCHEDULE_H_

#include <cstdint>

namespace llm {
namespace train {

struct ScheduleConfig {
  float max_learning_rate = 3e-4f;

  // Нижняя граница как доля от максимума. Доводить скорость ровно до нуля
  // незачем: последние шаги тогда не делают ничего.
  float min_ratio = 0.1f;

  int64_t warmup_steps = 100;
  int64_t total_steps = 2000;
};

// step считается от нуля.
float learning_rate_at(const ScheduleConfig& config, int64_t step);

}  // namespace train
}  // namespace llm

#endif  // LLM_TRAIN_SCHEDULE_H_
