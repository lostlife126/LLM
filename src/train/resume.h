// Снимок прерванного обучения.
//
// Обычный чекпоинт для этого не годится, и причина не очевидна. В чекпоинт
// пишется ЛУЧШАЯ модель по проверочным потерям, а продолжать надо с
// ПОСЛЕДНЕЙ: если прогон дошёл до тысяча четырёхсотого шага, а лучшим был
// тысячный, возобновление с чекпоинта — это откат на четыреста шагов назад.
// Поэтому снимок отдельный и хранит другое.
//
// Что в нём лежит:
//
//   последние веса      — то, с чего продолжать;
//   моменты Адама       — без них первые сотни шагов идут вслепую: оптимизатор
//                         заново копит оценки, которые уже были посчитаны;
//   номер шага          — от него зависят и расписание скорости, и поправка на
//                         смещение моментов;
//   лучшее значение     — чтобы возобновлённый прогон не затёр уже найденный
//                         лучший чекпоинт худшим.
//
// Чего в нём нет и почему. Состояние генератора, задающего порядок батчей, не
// сохраняется: вместо тысячи слов внутреннего состояния mt19937_64 порядок
// проще переиграть. Генератор создаётся с тем же зерном, и выборка
// прокручивается столько раз, сколько шагов уже сделано. Это не «примерно то
// же самое», а ровно то же самое по построению, и стоит миллисекунды.
//
// Файл отдельный от чекпоинта ещё и по размеру: моменты втрое увеличивают
// объём, а тому, кто хочет просто запустить модель, они не нужны.

#ifndef LLM_TRAIN_RESUME_H_
#define LLM_TRAIN_RESUME_H_

#include <cstdint>
#include <string>

#include "nn/model.h"
#include "train/optimizer.h"

namespace llm {
namespace train {

struct ResumeState {
  int64_t step = 0;
  float best_validation_loss = 0.0f;
  int64_t best_step = 0;
};

// Есть ли снимок по этому пути.
bool resume_exists(const std::string& path);

void save_resume(const std::string& path, nn::Model* model,
                 const AdamW& optimizer, const ResumeState& state);

// Загружает веса в модель и моменты в оптимизатор. Конфигурация модели обязана
// совпадать с записанной: продолжать обучение другой модели бессмысленно.
ResumeState load_resume(const std::string& path, nn::Model* model,
                        AdamW* optimizer);

}  // namespace train
}  // namespace llm

#endif  // LLM_TRAIN_RESUME_H_
