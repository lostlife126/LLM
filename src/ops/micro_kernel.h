// Микроядро GEMM: плитка mr x nr, накапливаемая в регистрах.
//
// Здесь происходит вся арифметика умножения матриц, поэтому здесь же лежит
// весь выигрыш от векторных инструкций. Остальное — блочные циклы и упаковка —
// существует затем, чтобы микроядро читало память подряд и не простаивало.
//
// Ядер несколько, и выбирается оно во время работы по возможностям процессора.
// Так бинарник остаётся переносимым: собранный на машине с AVX-512, он не
// падает с SIGILL там, где его нет, а берёт ядро попроще. Цена — косвенный
// вызов один раз на плитку, то есть раз в kc умножений с накоплением; на
// фоне самой плитки это не видно.
//
// Размеры плитки у каждого ядра свои, и от них зависит раскладка упакованных
// панелей. Поэтому упаковка параметризована mr и nr, а не зашита константами:
// иначе смена ядра молча ломала бы раскладку.

#ifndef LLM_OPS_MICRO_KERNEL_H_
#define LLM_OPS_MICRO_KERNEL_H_

#include <cstdint>

namespace llm {
namespace ops {

// Считает плитку mr x nr произведения и прибавляет alpha * плитку к C.
//
// apanel — mr значений на каждый шаг глубины, подряд;
// bpanel — nr значений на каждый шаг глубины, подряд;
// rows, cols — сколько строк и столбцов плитки реально попадают в C. Панели
// дополнены нулями, поэтому считается всегда полная плитка, а записывается
// только действительная часть.
using MicroKernelFn = void (*)(int64_t kc, const float* apanel,
                               const float* bpanel, float alpha, float* c,
                               int64_t ldc, int64_t rows, int64_t cols);

struct MicroKernel {
  int64_t mr = 0;
  int64_t nr = 0;
  MicroKernelFn run = nullptr;
  const char* name = "";

  // Использует ли ядро умножение с накоплением одной инструкцией.
  //
  // Признак нужен не для выбора ядра, а для проверки. Векторные ядра дают
  // побитово одинаковый результат — плитки у них разной формы, но порядок
  // накопления по глубине один и тот же, и умножение с накоплением у всех
  // слитное, с одним округлением. Скалярное ядро собирается под базовый
  // x86-64, где инструкции FMA нет, и делает умножение и сложение отдельно —
  // с двумя округлениями. Поэтому от векторных оно отличается, и требовать
  // от него побитового совпадения было бы неверно.
  bool fused = false;
};

// Лучшее ядро для этого процессора. Считается один раз.
const MicroKernel& best_micro_kernel();

// Все собранные ядра, включая недоступные на этом процессоре. Нужны замеру:
// сравнивать надо измерением, а не предположением, что шире значит быстрее.
// Недоступные помечены нулевым run.
struct MicroKernelChoice {
  MicroKernel kernel;
  bool available = false;
};
const MicroKernelChoice* all_micro_kernels(int* count);

// Принудительный выбор ядра — только для замера, который обязан сравнить
// ядра между собой, а не поверить, что шире значит быстрее. nullptr
// возвращает автоматический выбор.
//
// Величина глобальная и менять её на ходу нельзя: предполагается, что замер
// делает это до запуска потоков.
void force_micro_kernel(const MicroKernel* kernel);

}  // namespace ops
}  // namespace llm

#endif  // LLM_OPS_MICRO_KERNEL_H_
