// Микроядро GEMM: плитка mr x nr, накапливаемая в регистрах.
//
// Здесь происходит вся арифметика умножения матриц, поэтому здесь же лежит
// весь выигрыш от векторных инструкций. Остальное — блочные циклы и упаковка —
// существует затем, чтобы микроядро читало память подряд и не простаивало.
//
// Ядер несколько, и выбирается оно во время работы по возможностям процессора.
// Так бинарник остаётся переносимым: собранный на машине с AVX-512, он не
// падает с SIGILL там, где его нет, а берёт ядро попроще. Цена — косвенный
// вызов один раз на плитку, то есть раз в kc умножений с накоплением; на
// фоне самой плитки это не видно.
//
// Размеры плитки у каждого ядра свои, и от них зависит раскладка упакованных
// панелей. Поэтому упаковка параметризована mr и nr, а не зашита константами:
// иначе смена ядра молча ломала бы раскладку.

#ifndef LLM_OPS_MICRO_KERNEL_H_
#define LLM_OPS_MICRO_KERNEL_H_

#include <cstdint>

#include "core/half.h"

namespace llm {
namespace ops {

// Считает плитку mr x nr произведения и прибавляет alpha * плитку к C.
//
// apanel — mr значений на каждый шаг глубины, подряд;
// bpanel — nr значений на каждый шаг глубины, подряд;
// rows, cols — сколько строк и столбцов плитки реально попадают в C. Панели
// дополнены нулями, поэтому считается всегда полная плитка, а записывается
// только действительная часть.
using MicroKernelFn = void (*)(int64_t kc, const float* apanel,
                               const float* bpanel, float alpha, float* c,
                               int64_t ldc, int64_t rows, int64_t cols);

// Транспонирующая упаковка панели.
//
// Половина упаковок в этом проекте — транспонирование. Панель A в обычном
// умножении лежит построчно, а микроядру нужен шаг по глубине; панель B во
// внимании лежит, наоборот, по ключам, потому что там считается Q * K^T. В
// обоих случаях чтение идёт подряд, а запись — с шагом в ширину панели, и
// поэлементно это самый дорогой цикл во всей упаковке: по замеру на нём
// теряется от двадцати до тридцати процентов скорости умножения.
//
// Обе задачи — одна и та же: блок из lanes строк по kc значений с шагом lda
// превращается в kc групп по lanes значений подряд. Для панели A lanes равно
// mr, для панели B — nr; больше между ними разницы нет, поэтому функция одна.
//
// rows — сколько строк блока действительные. Остальные заполняются нулями:
// микроядро считает всегда полную плитку, а нули не портят сумму.
using PackTransposeFn = void (*)(const float* src, int64_t lda, int64_t lanes,
                                 int64_t rows, int64_t kc, float* dst);

// Микроядро прямого пути: A читается построчно, как лежит, без упаковки.
//
// Упаковка существует затем, чтобы микроядро читало память подряд. Когда вся
// задача помещается в кэш, это перестаёт что-либо значить: читать «не подряд»
// из L1 стоит столько же, а упаковка остаётся чистым накладным расходом. По
// замеру на формах внимания — от двадцати до восьмидесяти процентов времени
// умножения.
//
// Отличие от упакованного ядра ровно одно: значения A берутся как
// a[ii * lda + p] вместо a[p * mr + ii]. Команда та же — рассылка одного
// значения по всем дорожкам, — меняется только адрес.
//
// Требования, за которые отвечает вызывающий:
//   cols == nr, то есть плитка по столбцам полная. Проверок границ внутри нет,
//   и чтение nr значений подряд из строки B обязано оставаться в матрице;
//   1 <= rows <= mr. Недостающие строки ядро берёт с последней действительной
//   и в C не записывает — так не нужен ни буфер нулей, ни чтение за границей.
using MicroKernelRowsFn = void (*)(int64_t kc, const float* a, int64_t lda,
                                   const float* b, int64_t bstride, float alpha,
                                   float* c, int64_t ldc, int64_t rows,
                                   int64_t cols);

// То же самое, но B лежит в половинной разрядности.
//
// Зачем отдельное ядро, а не преобразование B заранее. При генерации по одному
// токену на каждый прочитанный вес приходится ровно одно умножение с
// накоплением: развернуть матрицу в float заранее значило бы прочитать её в
// половинной разрядности, записать в обычной и прочитать снова — вдвое больше
// байт, чем сейчас, вместо вдвое меньше. Развёртывание обязано происходить
// внутри ядра, в регистрах, между загрузкой и умножением.
//
// Побитовая воспроизводимость при этом сохраняется, и это не случайность.
// Развёртывание половинной разрядности в float точное: каждое значение
// представимо. Значит после него идут ровно те же умножения с накоплением в
// том же порядке, что и у обычного ядра, которому дали уже округлённые веса, —
// и результат совпадает побитово. Единственное численное отличие от fp32 —
// само округление весов, а оно одинаково на любой машине.
//
// Требования к вызывающему те же, что у ядра выше.
using MicroKernelRowsHalfFn = void (*)(int64_t kc, const float* a, int64_t lda,
                                       const Half* b, int64_t bstride,
                                       float alpha, float* c, int64_t ldc,
                                       int64_t rows, int64_t cols);

struct MicroKernel {
  int64_t mr = 0;
  int64_t nr = 0;
  MicroKernelFn run = nullptr;
  MicroKernelRowsFn run_rows = nullptr;
  MicroKernelRowsHalfFn run_rows_half = nullptr;
  PackTransposeFn pack_transpose = nullptr;
  const char* name = "";

  // Использует ли ядро умножение с накоплением одной инструкцией.
  //
  // Признак нужен не для выбора ядра, а для проверки. Векторные ядра дают
  // побитово одинаковый результат — плитки у них разной формы, но порядок
  // накопления по глубине один и тот же, и умножение с накоплением у всех
  // слитное, с одним округлением. Скалярное ядро собирается под базовый
  // x86-64, где инструкции FMA нет, и делает умножение и сложение отдельно —
  // с двумя округлениями. Поэтому от векторных оно отличается, и требовать
  // от него побитового совпадения было бы неверно.
  bool fused = false;
};

// Лучшее ядро для этого процессора. Считается один раз.
const MicroKernel& best_micro_kernel();

// Все собранные ядра, включая недоступные на этом процессоре. Нужны замеру:
// сравнивать надо измерением, а не предположением, что шире значит быстрее.
// Недоступные помечены нулевым run.
struct MicroKernelChoice {
  MicroKernel kernel;
  bool available = false;
};
const MicroKernelChoice* all_micro_kernels(int* count);

// Принудительный выбор ядра — только для замера, который обязан сравнить
// ядра между собой, а не поверить, что шире значит быстрее. nullptr
// возвращает автоматический выбор.
//
// Величина глобальная и менять её на ходу нельзя: предполагается, что замер
// делает это до запуска потоков.
void force_micro_kernel(const MicroKernel* kernel);

}  // namespace ops
}  // namespace llm

#endif  // LLM_OPS_MICRO_KERNEL_H_
