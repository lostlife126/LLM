// Дропаут: случайное зануление части значений при обучении.
//
// Смысл приёма в том, что сеть не может положиться ни на один отдельный канал
// — он в любой момент может исчезнуть, — и вынуждена распределять
// представление по многим. Получается что-то вроде усреднения по ансамблю
// сетей, которые отличаются выключенными каналами.
//
// Реализация «обратная»: делим на вероятность сохранения сразу при обучении, а
// не умножаем на неё при выводе. Тогда инференс — это в точности та же
// формула без дропаута, и ничего переключать не надо. Ошибиться здесь легко и
// последствия неочевидны: модель будет работать, но выдавать систематически
// заниженные активации.
//
// Маска возвращается наружу и хранится лентой: обратный проход обязан занулить
// ровно те же элементы, что и прямой. Сгенерировать её заново нельзя — это
// был бы другой дропаут.

#ifndef LLM_OPS_DROPOUT_H_
#define LLM_OPS_DROPOUT_H_

#include "core/random.h"
#include "core/tensor.h"

namespace llm {
namespace ops {

// Маска из нулей и единиц: единица с вероятностью 1 - probability.
Tensor dropout_mask(const Shape& shape, float probability, Rng* rng);

// input * mask / (1 - probability).
Tensor dropout_forward(const Tensor& input, const Tensor& mask,
                       float probability);

// Градиент той же формулы: он линеен, поэтому выражение то же самое.
Tensor dropout_backward(const Tensor& grad_output, const Tensor& mask,
                        float probability);

}  // namespace ops
}  // namespace llm

#endif  // LLM_OPS_DROPOUT_H_
