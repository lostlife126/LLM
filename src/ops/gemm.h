// Умножение матриц: C = alpha * op(A) * op(B) + beta * C.
//
// Всё в row-major. op(A) имеет размер m×k, op(B) — k×n, C — m×n.
// lda, ldb, ldc — шаг строки (leading dimension) матрицы в памяти, заданный
// ДО транспонирования: при transpose_a матрица A лежит как k×m с шагом строки
// lda. Такая развязка формы и размещения позволяет передавать сюда
// транспонированный вид тензора без копирования данных.
//
// Две реализации с одинаковой семантикой:
//
//   gemm_naive — тройной цикл. Остаётся в проекте навсегда как эталон: любая
//                оптимизированная версия сверяется с ней в тестах.
//   gemm       — блочная версия с упаковкой панелей.

#ifndef LLM_OPS_GEMM_H_
#define LLM_OPS_GEMM_H_

#include <cstdint>

#include "core/half.h"

namespace llm {
namespace ops {

// Учёт прочитанных умножением байт.
//
// Включается переменной окружения LLM_TRAFFIC. Выключенный не стоит ничего:
// признак читается один раз, а считается поблочно, не поэлементно.
//
// Зачем нужен. Вопрос «где лежат байты» решает, куда имеет смысл ставить
// сжатие весов, и решать его надо числом. Именно этот счётчик показал, что при
// генерации по одному токену веса дают две трети всего чтения, а при обучении
// батчами — четверть, и что накопитель C в обучении доминирует над обоими.
struct GemmTraffic {
  bool enabled = false;
  long long a_bytes = 0;  // левая матрица, то есть активации
  long long b_bytes = 0;  // правая, то есть веса
  long long c_bytes = 0;  // накопитель, чтение и запись
};

void reset_traffic();
GemmTraffic traffic();

// Принудительный порог прямого пути по числу строк — только для замера.
//
// Порог существует потому, что при малом m упаковка блочного пути не
// окупается: она стоит k * n работы при m * k * n самого умножения. Значение
// подобрано замером и записано константой в gemm.cpp.
//
// Мерить его надо на каждой машине, а не переносить с одной: замер на
// Raspberry Pi 5 показал, что там блочный путь при m = 16 обгонял прямой при
// m = 1, делая в шестнадцать раз больше умножений. Вдобавок упаковка B с тех
// пор стала читать матрицу подряд, а не с шагом в строку, — то есть блочный
// путь ускорился, и прежний выбор мог перестать быть верным.
//
// Отрицательное значение возвращает подобранный порог. Величина глобальная и
// менять её на ходу нельзя: предполагается, что замер делает это до запуска
// потоков.
void force_direct_max_rows(int64_t rows);

void gemm_naive(bool transpose_a, bool transpose_b, int64_t m, int64_t n,
                int64_t k, float alpha, const float* a, int64_t lda,
                const float* b, int64_t ldb, float beta, float* c, int64_t ldc);

void gemm(bool transpose_a, bool transpose_b, int64_t m, int64_t n, int64_t k,
          float alpha, const float* a, int64_t lda, const float* b, int64_t ldb,
          float beta, float* c, int64_t ldc);

// То же самое, но B лежит в половинной разрядности.
//
// Транспонирование B не поддерживается: транспонированный B бывает во
// внимании, то есть у активаций, а половинная разрядность здесь заведена для
// весов.
//
// Численно это ровно gemm, которому дали веса, уже прошедшие округление:
// развёртывание половинной разрядности точное, и порядок накопления не
// меняется. Проверяется тестом на побитовое совпадение, а не обещанием.
//
// Где это быстрее, а где нет (замер на четырёх потоках, формы модели):
//
//   m <= 8       1.13 - 1.44 раза быстрее — генерация по токену;
//   m = 16..64   0.43 - 0.67, то есть медленнее;
//   m в тысячах  0.99, вровень.
//
// На aarch64 разброс шире в обе стороны, и это стоит знать заранее. Замер на
// Raspberry Pi 5 при m = 1: на широких матрицах выигрыш доходит до 3.2 раза,
// потому что там всё упирается в память, а на узких, помещающихся в кэш, выходит
// 0.88 — экономить нечего, а две команды FCVTL на каждые восемь весов остаются,
// и идут они через те же конвейеры, что и умножение с накоплением. У F16C на
// x86 для преобразования отдельный порт, поэтому там та же строка даёт 1.22.
//
// Провал в середине не случайность и не недоделка, а устройство путей. При
// m <= 8 считается прямым путём, где веса читаются как лежат, и половинная
// разрядность даёт ровно то, ради чего заведена: вдвое меньше байт. Дальше
// включается блочный путь с упаковкой панелей, и там веса приходится
// разворачивать в обычную разрядность при записи в панель — это дороже, чем
// скопировать готовые float. Стоимость упаковки одна на весь проход, поэтому с
// ростом m она размывается и отношение возвращается к единице.
//
// Отсюда и область применения: веса половинной разрядности — для инференса.
// В обучении они не дают ничего, а по замеру сходимости ещё и требуют
// эталонной копии в fp32, так что смысла там нет вдвойне.
void gemm_half_b(bool transpose_a, int64_t m, int64_t n, int64_t k, float alpha,
                 const float* a, int64_t lda, const Half* b, int64_t ldb,
                 float beta, float* c, int64_t ldc);

}  // namespace ops
}  // namespace llm

#endif  // LLM_OPS_GEMM_H_
