// RoPE — поворотное кодирование позиции.
//
// Идея: вместо того чтобы прибавлять к вектору отдельный вектор позиции,
// повернуть пары его координат на угол, пропорциональный позиции. Тогда
// скалярное произведение запроса и ключа зависит только от РАЗНОСТИ их
// позиций — относительное кодирование получается само собой, из геометрии, а
// не из дополнительных параметров. Обучаемых весов у RoPE нет вообще.
//
// Координаты разбиваются на пары (x[2i], x[2i+1]), и пара i поворачивается на
// угол pos * theta^(-2i/d). Низкие i вращаются быстро, высокие — медленно,
// поэтому вектор кодирует позицию на разных масштабах сразу.
//
// Конвенция здесь — соседние пары, как в исходной статье. В реализации
// HuggingFace пары составляются иначе: x[i] с x[i + d/2]. Результаты
// эквивалентны с точностью до перестановки координат, но веса между этими
// конвенциями напрямую не переносятся.

#ifndef LLM_OPS_ROPE_H_
#define LLM_OPS_ROPE_H_

#include <cstdint>

#include "core/tensor.h"

namespace llm {
namespace ops {

// input: (..., seq, head_dim), head_dim обязан быть чётным.
// position_offset сдвигает позиции: при генерации с KV-кэшем запрос один, а
// его настоящая позиция — длина уже накопленного контекста.
Tensor rope(const Tensor& input, int64_t position_offset, float theta);

// Поворот — ортогональное преобразование, поэтому обратный проход есть поворот
// на тот же угол в другую сторону. Отдельной математики не требуется.
Tensor rope_backward(const Tensor& grad_output, int64_t position_offset,
                     float theta);

}  // namespace ops
}  // namespace llm

#endif  // LLM_OPS_ROPE_H_
