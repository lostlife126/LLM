// Экспонента и сигмоида массивом, с векторными реализациями.
//
// Зачем своя экспонента. По профилю шага обучения silu, softmax и
// cross-entropy вместе дают около пятой части времени, и внутри них почти всё
// уходит в std::exp, вызываемый на каждый элемент по одному. Векторизовать его
// компилятор не может: expf — вызов функции из libm, а не выражение, и
// автовекторизатор через вызов не переступает.
//
// Устройство ровно такое же, как у микроядер GEMM: несколько реализаций под
// разные наборы инструкций и выбор во время работы. С одной поправкой,
// которую пришлось внести по результатам замера.
//
// Реализаций здесь четыре, а не три, и скалярных из них две. Сначала была
// одна — свой многочлен, — и она служила и эталоном, и запасным путём для
// процессора без AVX2. Замер это опроверг: свой скалярный многочлен вдвое
// медленнее std::exp. У libm внутри не только многочлен, но и таблица на 128
// входов, за счёт которой цепочка зависимых операций вдвое короче, а у нас
// пятнадцать операций подряд, каждая ждёт предыдущую. То есть запасной путь,
// существующий ради старых процессоров, на них же оказывался хуже того, что
// заменял.
//
// Поэтому запасным путём стал std::exp, а свой скалярный многочлен остался
// тем, чем он полезен: читаемой записью алгоритма и эталоном, с которым в
// тестах сверяются векторные реализации. Автоматически он не выбирается —
// правило «последнее доступное в таблице лучшее» ставит его первым.
//
// Договор о числах здесь тот же, что у микроядер GEMM: векторные реализации
// совпадают между собой **побитово**, скалярная отличается на одно округление.
// Отличается она потому, что собирается под базовый x86-64, где инструкции
// умножения с накоплением (FMA) нет, а векторные её используют — и в
// многочлене, и в приведении аргумента, где она заодно и точнее.
//
// Одна ловушка на этом пути стоила отладки и заслуживает записи. Сначала
// многочлен был написан раздельными умножением и сложением во всех трёх
// реализациях — нарочно, чтобы все три совпали. AVX2 и скалярная совпали, а
// AVX-512 разошлась на четырёх значениях из тысячи. Причина: GCC сам склеивает
// умножение со сложением в FMA, даже когда они написаны отдельными
// интринсиками, — если целевой набор инструкций её содержит. У ветви AVX2
// целевым был указан только avx2, FMA в нём нет, и склейки не происходило; у
// AVX-512 она есть всегда. То есть «написать раздельно» вовсе не значит
// «получить раздельно», и единственный надёжный способ управлять этим —
// написать FMA явно там, где она нужна. Так и сделано.
//
// Сумма при этом никогда не считается внутри векторного ядра. Сложить восемь
// дорожек и сложить восемь чисел подряд — разный порядок сложений и разный
// результат; суммирование остаётся обычным последовательным циклом, а
// векторным остаётся только поэлементное.

#ifndef LLM_OPS_FAST_EXP_H_
#define LLM_OPS_FAST_EXP_H_

#include <cstdint>

namespace llm {
namespace ops {

// out[i] = exp(in[i] - shift).
//
// Сдвиг — часть интерфейса, а не удобство: и softmax, и cross-entropy всегда
// вычитают максимум строки, и отдельный проход по памяти ради вычитания стоил
// бы больше самой экспоненты.
void exp_shifted(const float* input, float shift, float* output, int64_t count);

// out[i] = exp(in[i]).
void exp_array(const float* input, float* output, int64_t count);

// out[i] = 1 / (1 + exp(-in[i])).
void sigmoid_array(const float* input, float* output, int64_t count);

// Одно значение эталонной скалярной реализацией — тем самым многочленом,
// который повторяют векторные. От них отличается на одно округление, от
// std::exp — на единицы последних разрядов.
float exp_scalar(float x);

// Реализация: пара функций и имя.
struct ExpKernel {
  void (*exp_shifted)(const float*, float, float*, int64_t) = nullptr;
  void (*sigmoid)(const float*, float*, int64_t) = nullptr;
  const char* name = "";

  // Использует ли реализация умножение с накоплением одной инструкцией.
  //
  // Признак нужен для проверки, а не для выбора. Реализации с FMA обязаны
  // совпадать между собой побитово: многочлен у них один и тот же, и
  // округлений тоже. Те, что без FMA, округляют дважды там, где эти
  // округляют один раз, и совпадать с ними не могут — от них требуется
  // близость, а не равенство.
  bool fused = false;
};

// Лучшая реализация для этого процессора. Считается один раз.
const ExpKernel& best_exp_kernel();

// Все собранные реализации, включая недоступные на этом процессоре. Нужны
// замеру и тесту на побитовое совпадение.
struct ExpKernelChoice {
  ExpKernel kernel;
  bool available = false;
};
const ExpKernelChoice* all_exp_kernels(int* count);

// Принудительный выбор — только для замера и тестов. nullptr возвращает
// автоматический выбор. Величина глобальная, менять её на ходу нельзя.
void force_exp_kernel(const ExpKernel* kernel);

}  // namespace ops
}  // namespace llm

#endif  // LLM_OPS_FAST_EXP_H_
