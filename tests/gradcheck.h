// Численная проверка градиентов.
//
// Для каждого элемента каждого входа считается центральная разность
// (f(x + h) - f(x - h)) / 2h и сравнивается с градиентом, который выдал
// обратный проход. Проверка ничего не знает об устройстве операции, поэтому
// ловит ошибки, которые невозможно заметить, глядя на формулу.
//
// О достижимой точности. Данные здесь float32, и это ставит предел снизу:
// вычитание двух близких значений f теряет значащие цифры (ошибка порядка
// eps * |f| / h при машинной точности 1.2e-7), а сама центральная разность
// приближает производную с ошибкой порядка h^2. Шаг h = 1e-2 балансирует эти
// два источника.
//
// Допуск подобран замером, а не оценкой сверху. На всех проверяемых операциях
// с заведомо верным обратным проходом наибольшее относительное расхождение —
// 1.16e-4, поэтому 1e-3 оставляет почти девятикратный запас и при этом ловит
// ошибку уже в десятые доли процента. Проверено внесением ошибки: обратный
// проход, ошибающийся на 0.2%, роняет 34 проверки из тридцати пяти.
//
// Относительное — значит относительное. Нормировка делит расхождение на
// наибольший градиент тензора, и нижняя граница у этого масштаба привязана не
// к единице, а к тому, что метод вообще способен различить: центральная
// разность вычитает два близких значения функции и делит на 2h, поэтому её
// собственный шум порядка eps * |f| / h. Граница в единицу, стоявшая здесь
// раньше, подменяла относительное сравнение абсолютным везде, где градиенты
// мельче её, — а так выходило в 38 случаях из 51, и та же ошибка в 0.2%
// ловилась тогда лишь двадцатью восемью проверками.
//
// Если какая-то операция потребует большего допуска, его лучше передать явно
// в этом тесте, чем ослаблять значение по умолчанию для всех.

#ifndef LLM_TESTS_GRADCHECK_H_
#define LLM_TESTS_GRADCHECK_H_

#include <cstdint>
#include <functional>
#include <string>
#include <vector>

#include "autograd/node.h"
#include "core/tensor.h"

namespace llm {
namespace testing {

struct GradCheckResult {
  bool ok = false;
  double max_error = 0.0;
  std::string detail;
};

// fn получает переменные, построенные из inputs, и обязана вернуть скаляр.
// Детерминированный случайный тензор: тесты должны воспроизводиться.
Tensor random_tensor(const Shape& shape, std::uint64_t seed, float low = -1.0f,
                     float high = 1.0f);

// Свёртка результата операции в скаляр со случайными весами.
//
// Простая сумма скрыла бы целый класс ошибок: backward, раздающий всем
// элементам одинаковый градиент вместо правильного, на сумме дал бы верный
// ответ. Случайные веса делают скаляр чувствительным к каждому элементу
// по отдельности.
autograd::Var weighted_sum(const autograd::Var& output, std::uint64_t seed);

GradCheckResult gradcheck(
    const std::function<autograd::Var(const std::vector<autograd::Var>&)>& fn,
    const std::vector<Tensor>& inputs, float step = 1e-2f,
    double tolerance = 1e-3);

}  // namespace testing
}  // namespace llm

// Проверяет градиенты и печатает подробности при расхождении.
#define LLM_EXPECT_GRADCHECK(fn, inputs)            \
  do {                                              \
    const ::llm::testing::GradCheckResult llm_gc_ = \
        ::llm::testing::gradcheck((fn), (inputs));  \
    LLM_CHECK_MSG(llm_gc_.ok, llm_gc_.detail);      \
  } while (false)

#endif  // LLM_TESTS_GRADCHECK_H_
