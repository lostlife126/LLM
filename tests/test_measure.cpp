// Методика замера.
//
// Через best_seconds проходит каждое число, которое проект печатает про
// скорость, — и она, как разбор аргументов до вчерашнего дня, не проверялась
// ничем. Проверить её стоит по той же причине: ошибка здесь не падает, а
// сдвигает результат, и сдвинутый результат выглядит как измеренный.
//
// Проверяется ровно то, что обещано в заголовке: один прогрев вне замера,
// kTrials независимых серий и МИНИМУМ по сериям. Последнее важнее всего —
// именно на нём держится довод «помехи бывают только в одну сторону», и
// подменись минимум средним или последним, числа стали бы оценкой занятости
// машины, а не её возможностей.

#include <chrono>
#include <cstdint>

#include "measure.h"
#include "testing.h"

namespace {

using Clock = std::chrono::steady_clock;

// Занять ровно столько времени по настенным часам. Вращение, а не сон:
// длительность сна операционная система соблюдает только снизу, и на коротких
// промежутках промахивается в разы — то есть «медленный» вызов оказался бы
// непредсказуемо медленным.
void burn(double seconds) {
  const Clock::time_point until =
      Clock::now() + std::chrono::duration_cast<Clock::duration>(
                         std::chrono::duration<double>(seconds));
  while (Clock::now() < until) {
  }
}

// Длительность «медленного» вызова. Выбрана так, чтобы уверенно отличаться от
// пустого вызова даже под qemu и санитайзерами, где пустой вызов стоит
// десятки микросекунд, а не доли.
const double kSlow = 0.005;

}  // namespace

LLM_TEST(Measure, WarmUpIsOutsideTheSeriesAndSeriesAreCounted) {
  // Нулевая длительность серии: цикл внутри серии сделан с постусловием,
  // поэтому каждая серия — ровно один вызов. Значит число вызовов и есть
  // прямое свидетельство того, сколько серий сделано и был ли прогрев.
  int calls = 0;
  bench::best_seconds([&calls]() { ++calls; }, 0.0);
  LLM_CHECK_MSG(calls == bench::kTrials + 1,
                "вызовов " << calls << ", а ожидалось " << bench::kTrials
                           << " серий плюс один прогрев");
}

LLM_TEST(Measure, TakesTheMinimumOverSeriesNotTheLastOrTheMean) {
  // Одна серия из пяти делается быстрой, остальные — медленными. Быстрая
  // стоит третьей: будь взят последний результат, ответ был бы медленным;
  // будь взято среднее — примерно четыре пятых медленного. Минимум обязан
  // дать быстрый.
  int calls = 0;
  const double best = bench::best_seconds(
      [&calls]() {
        ++calls;
        // Ноль — прогрев, дальше серии по одному вызову. Третья серия —
        // четвёртый вызов подряд.
        if (calls != 4) {
          burn(kSlow);
        }
      },
      0.0);

  // Проверка непуста: медленный вызов действительно медленный, и порог между
  // ним и быстрым существует. Без этой строки тест прошёл бы и на часах,
  // которые всегда возвращают ноль.
  int slow_calls = 0;
  const double all_slow = bench::best_seconds(
      [&slow_calls]() {
        ++slow_calls;
        burn(kSlow);
      },
      0.0);
  LLM_CHECK_MSG(all_slow > kSlow * 0.5,
                "медленная серия отмерена как " << all_slow
                                                << " с — часы не идут");

  LLM_CHECK_MSG(best < all_slow * 0.5,
                "лучшее время " << best << " с при медленном " << all_slow
                                << " с: похоже, берётся не минимум по сериям");
}
